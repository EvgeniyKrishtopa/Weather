export const getCuratedCityList = (
  countryIso: string,
): readonly CuratedCityName[] => {
  if (!isSupportedCountryIso(countryIso)) {
    return [];
  }

  return curatedCityNamesByCountry[countryIso];
};

export const getCuratedCityValues = (countryIso: string): string[] =>
  getCuratedCityList(countryIso).map(({ value }) => value);

export const getCityDisplayName = (
  cityName: string,
  countryIso: string,
  language: SupportedLanguage,
): string => {
  const supportedCountryIso = normalizeSupportedCountryIso(countryIso);
  const cityMatch = curatedCityNamesByCountry[supportedCountryIso].find(
    ({ value }) => value === cityName,
  );

  return cityMatch?.labels[language] ?? cityName;
};

export const createCityOptions = (
  cities: string[],
  countryIso: string,
  language: SupportedLanguage,
): CityOption[] =>
  cities.map((cityName) => ({
    value: cityName,
    label: getCityDisplayName(cityName, countryIso, language),
  }));
